-- tabel : categories , suppliers , products , stock_transactions
-- Relationship : (CATEGORY 1:N PRODUCT ) AND  ( PRODUCT 1:N STOCK_TRANSACTION )


--1. CATEGORIES
--- category_id — Primary Key
--- category_name

--2. SUPPLIERS
--- supplier_id — Primary Key
--- supplier_name
--- phone
--- email

--3. PRODUCTS
--- product_id — Primary Key
--- product_name
--- category_id — Foreign Key
--- supplier_id — Foreign Key
--- quantity
--- unit_price
--- reorder_level

--4. STOCK_TRANSACTIONS
--- transaction_id — Primary Key
--- product_id — Foreign Key
--- transaction_type
--- quantity
--- transaction_date 

-- 1. CATEGORIES
CREATE TABLE categories (
    category_id   int ,
    category_name VARCHAR2(100) NOT NULL,

    CONSTRAINT pk_categories PRIMARY KEY (category_id),
    CONSTRAINT uq_categories_name UNIQUE (category_name)
);

-- 2. SUPPLIERS
CREATE TABLE suppliers (
    supplier_id   int,
    supplier_name VARCHAR2(120) NOT NULL,
    phone         VARCHAR2(20),
    email         VARCHAR2(120),

    CONSTRAINT pk_suppliers PRIMARY KEY (supplier_id),
    CONSTRAINT uq_suppliers_email UNIQUE (email)
);


-- 3. PRODUCTS
CREATE TABLE products (
    product_id    int GENERATED BY DEFAULT AS IDENTITY,
    product_name  VARCHAR2(120) NOT NULL,
    category_id   NUMBER NOT NULL,
    supplier_id   NUMBER NOT NULL,
    quantity      NUMBER(10) DEFAULT 0 NOT NULL,
    unit_price    NUMBER(10, 2) NOT NULL,
    reorder_level NUMBER(10) DEFAULT 5 NOT NULL,

    CONSTRAINT pk_products PRIMARY KEY (product_id),
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id) REFERENCES categories(category_id),
    CONSTRAINT fk_products_supplier
        FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id),
    CONSTRAINT ck_products_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_products_price CHECK (unit_price >= 0),
    CONSTRAINT ck_products_reorder CHECK (reorder_level >= 0)
);

-- 4. STOCK_TRANSACTIONS
CREATE TABLE stock_transactions (
    transaction_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    product_id       NUMBER NOT NULL,
    transaction_type VARCHAR2(3) NOT NULL,
    quantity         NUMBER(10) NOT NULL,
    transaction_date DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_stock_transactions PRIMARY KEY (transaction_id),
    CONSTRAINT fk_transactions_product
        FOREIGN KEY (product_id) REFERENCES products(product_id),
    CONSTRAINT ck_transaction_type
        CHECK (transaction_type IN ('IN', 'OUT')),
    CONSTRAINT ck_transaction_quantity CHECK (quantity > 0)
);

